"""Writes CHSaveMan/TitleFont.h: CHGfx's SansBold12 cut to 0x20..0x5A (space, digits, capitals drawn;
punctuation kept as empty glyphs).
The titles are capitals (a save code with other characters is drawn in the small font); this saves ~0.5 KB of
flash. The glyphs are the library's, byte for byte. Run from the project root:
    python CHSaveMan/tools/gen_titlefont.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "chgame/platform/board/arduino/CHGame/libraries/CHGfx/src/fonts/CHGfx_SansBold12.h"
OUT = ROOT / "CHSaveMan/TitleFont.h"
LAST = 0x5A

s = SRC.read_text(encoding="utf-8")
bm = s[s.index("Bitmaps[] = {"):]
bm = bm[:bm.index("};")]
data = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", bm)]
gl = s[s.index("Glyphs[] = {"):]
gl = gl[:gl.index("};")]
rows = re.findall(r"\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\},\s*/\* 0x([0-9A-F]{2})", gl)
assert int(rows[0][6], 16) == 0x20 and len(rows) == 95, len(rows)
keep = [r for r in rows if int(r[6], 16) <= LAST]


def drawn(c):                          # the characters with a picture: space, digits, capitals (0.20)
    return c == 0x20 or 0x30 <= c <= 0x39 or 0x41 <= c <= 0x5A


bits, glyphs = [], []
for r in keep:
    c = int(r[6], 16)
    w, h = int(r[1]), int(r[2])
    if drawn(c):
        n = (w * h + 7) // 8
        glyphs.append((len(bits), *r[1:6], r[6]))
        bits += data[int(r[0]):int(r[0]) + n]
    else:                              # punctuation: no picture (titleText draws such a title in the small font)
        glyphs.append((0, 0, 0, r[3], 0, 0, r[6]))
end = len(bits)
data = bits
first = re.search(r"0x20, 0x7E, (\d+)", s)
assert first, "font struct"

o = ["// GENERATED by tools/gen_titlefont.py from CHGfx's fonts/CHGfx_SansBold12.h (DejaVu Sans Bold 12 px; see that",
     "// file's notice): only 0x20..0x%02X, the same glyphs; punctuation has no picture. Do not edit." % LAST,
     "#pragma once", "#include <CHGfx_gfxfont.h>", "", "static const uint8_t TitleFontBitmaps[] = {"]
for i in range(0, end, 12):
    o.append("    " + " ".join("0x%02X," % b for b in data[i:i + 12]))
o += ["};", "", "static const GFXglyph TitleFontGlyphs[] = {"]
for r in glyphs:
    o.append("    { %s, %s, %s, %s, %s, %s },   /* 0x%s */" % (*r[:6], r[6]))
o += ["};", "", "static const GFXfont TitleFont = {", "    (uint8_t  *)TitleFontBitmaps,", "    (GFXglyph *)TitleFontGlyphs,",
      "    0x20, 0x%02X, %s" % (LAST, first.group(1)), "};", ""]
OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
print(OUT, end, "bitmap bytes,", len(keep), "glyphs")
