"""Names.h: the four-character save codes (save::magic("XXXX")) and the game each belongs to.

    python tools/gen_names.py <CHGame checkout>

Only public games, so the table can ship: CHGame's own examples (<checkout>/platform/board/arduino/CHGame/
libraries/CHGame/examples/Games) and tools/names_extra.txt (`CODE=NAME` lines, public games only; they win).
Every other game's name is learned on the card: FIND GAME NAMES reads each .CHG's title and appends it to
SAVENAME.TXT. Writes Names.h beside the sketch: never edit it by hand. Prints the codes two games share.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKETCH = HERE.parent
MAGIC = re.compile(r'save::magic\("([^"]{4})"\)')
SKIP = {"build", "out", "__pycache__", ".git"}
EXAMPLES = Path("platform/board/arduino/CHGame/libraries/CHGame/examples/Games")
NAME_LEN = 14
EXTS = {".ino", ".cpp", ".h", ".c"}


def title_for(f, root):
    for d in f.parents:
        j = d / "chgame.json"
        if j.exists():
            try:
                t = json.loads(j.read_text(encoding="utf-8")).get("title")
                if t:
                    return t
            except (ValueError, OSError):
                pass
        if d == root:
            break
    return f.parent.name


def scan(root):
    found = {}
    for f in root.rglob("*"):
        if f.suffix not in EXTS or any(p in SKIP for p in f.relative_to(root).parts[:-1]):
            continue
        try:
            text = f.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for code in MAGIC.findall(text):
            found.setdefault(code, set()).add(title_for(f, root))
    return found


def clean(name):
    n = re.sub(r"[^A-Z0-9 .'&+-]", "", name.upper())
    return n[:NAME_LEN].strip()


def main():
    if len(sys.argv) != 2 or not (Path(sys.argv[1]) / EXAMPLES).is_dir():
        raise SystemExit(__doc__)
    roots = [Path(sys.argv[1]) / EXAMPLES]
    names = {}
    clash = []
    for r in roots:
        for code, titles in scan(r).items():
            if code in names and names[code] not in titles:
                clash.append((code, names[code], sorted(titles)))
            if len(titles) > 1:
                clash.append((code, "(same folder)", sorted(titles)))
            names.setdefault(code, sorted(titles)[0])
    extra = HERE / "names_extra.txt"
    if extra.exists():
        for line in extra.read_text(encoding="utf-8").splitlines():
            line = line.split("#")[0].strip()
            if "=" in line:
                c, n = line.split("=", 1)
                if len(c) == 4:
                    names[c] = n.strip()
    for c, n in sorted(names.items()):
        if len(clean(n)) < len(re.sub(r"[^A-Z0-9 .'&+-]", "", n.upper()).strip()):
            print(f"  {c}: '{n}' is cut to '{clean(n)}': give it a short name in names_extra.txt")
    rows = sorted((c, clean(n)) for c, n in names.items())
    out = ["// The save codes of the CHGame games and their names. GENERATED by tools/gen_names.py: do not edit.",
           "// Add a game by name in tools/names_extra.txt (CODE=NAME) and run the generator again.",
           "#pragma once", "#include <stdint.h>", "",
           "struct SaveName { char code[4]; char name[%d]; };   // (the app's learned names)" % (NAME_LEN + 1),
           "// Packed (less flash than a table of SaveName): 4 code characters, the name, a NUL; \"\" ends it.",
           "static const char SAVE_NAMES[] ="]

    def lit(t):
        return '"' + t.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?") + '"'
    for c, n in rows:
        out.append('    %s %s "\\0"' % (lit(c), lit(n)))
    out += ['    "";', "static const int SAVE_NAME_COUNT = %d;" % len(rows), ""]
    (SKETCH / "Names.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(rows)} codes -> Names.h")
    for c, a_, b_ in clash:
        print(f"  shared code {c}: {a_} / {b_}")


if __name__ == "__main__":
    main()
